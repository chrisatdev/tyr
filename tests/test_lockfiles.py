class KeyShapesTest(unittest.TestCase):
    def test_pnpm_keys_across_lockfile_versions(self):
        cases = {
            "/is-number/7.0.0": ("is-number", "7.0.0"),                        # v5
            "/@babel/core/7.22.5": ("@babel/core", "7.22.5"),                  # v5 scoped
            "/@a/b/1.0.0_@types+node@20.1.0": ("@a/b", "1.0.0"),               # v5 peer suffix
            "/is-number@7.0.0": ("is-number", "7.0.0"),                        # v6
            "/@a/b@1.0.0(react@18.2.0)": ("@a/b", "1.0.0"),                    # v6 scoped + peer
            "'@cacheable/memory@2.2.0'": ("@cacheable/memory", "2.2.0"),        # v9 quoted scoped
            "minimist@1.2.5": ("minimist", "1.2.5"),                           # v9
            "/al@npm:real@1.0.0": ("real", "1.0.0"),                           # v6 alias
            "/al@npm:@s/real@1.0.0(react@18.2.0)": ("@s/real", "1.0.0"),       # v6 scoped alias + peer
            "al@npm:real@1.0.0": ("real", "1.0.0"),                            # v9 alias
            "pkg@git+ssh://git@github.com/o/r.git#abc": ("pkg", "git+ssh://git@github.com/o/r.git#abc"),
        }
        for key, expected in cases.items():
            self.assertEqual(_pnpm_key(key), expected, key)
        self.assertIsNone(_pnpm_key("github.com/owner/repo/0123abc"))  # v5 git entry

    def test_name_ends_at_the_first_at_after_the_scope(self):
        self.assertEqual(_split_name_version("fsevents@patch:fsevents@npm%3A2.3.2#hash"), ("fsevents", "patch:fsevents@npm%3A2.3.2#hash"))
        self.assertEqual(_split_name_version("@scope/name@npm:1.2.3"), ("@scope/name", "npm:1.2.3"))
        self.assertEqual(_split_name_version("name"), ("name", ""))


class PythonTest(unittest.TestCase):
    PYPI = {"certifi": "2026.10.23", "chardet": "3.0.4", "idna": "2.10", "requests": "2.25.0", "urllib3": "1.26.20"}

    def test_poetry_lock(self):
        deps, _ = found("poetry", "poetry.lock")
        expected = {(n, v, None) for n, v in self.PYPI.items()} | {("iniconfig", "2.0.0", None)}
        self.assertEqual(deps, expected)

    def test_poetry_skips_every_non_registry_source(self):
        import tempfile, shutil
        directory = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, directory)
        packages = ['[[package]]\nname = "requests"\nversion = "2.25.0"\n']
        for kind in ["legacy", "git", "file", "directory", "url"]:
            packages.append(f'[[package]]\nname = "{kind}-pkg"\nversion = "1.0.0"\n[package.source]\ntype = "{kind}"\nurl = "x"\n')
        (directory / "poetry.lock").write_text("\n".join(packages) + "\n[metadata]\nlock-version = \"2.0\"\n")
        result = parse_lockfile(directory / "poetry.lock")
        self.assertEqual([d["name"] for d in result.dependencies], ["requests"])
        self.assertEqual(sorted(result.skipped), sorted(f"{k}-pkg" for k in ["legacy", "git", "file", "directory", "url"]))

    def test_pipfile_lock_separates_default_and_develop(self):
        deps, _ = found("pipenv", "Pipfile.lock")
        expected = {(n, v, "prod") for n, v in self.PYPI.items()} | {("iniconfig", "2.0.0", "dev")}
        self.assertEqual(deps, expected)

    def test_uv_lock_skips_the_virtual_project(self):
        deps, skipped = found("uv", "uv.lock")
        expected = {(n, v, None) for n, v in self.PYPI.items()} | {("iniconfig", "2.0.0", None)}
        self.assertEqual(deps, expected)
        self.assertEqual(skipped, ["canary"])

    def test_pip_compile_requirements_with_hashes(self):
        deps, _ = found("pipcompile", "requirements.txt")
        self.assertEqual(deps, {(n, v, None) for n, v in self.PYPI.items()})


