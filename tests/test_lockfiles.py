class RecordShapeTest(unittest.TestCase):
    def test_every_dependency_is_exact_typed_and_sourced(self):
        expected_type = {
            "package-lock.json": "npm", "pnpm-lock.yaml": "npm", "yarn.lock": "npm",
            "poetry.lock": "pypi", "Pipfile.lock": "pypi", "uv.lock": "pypi", "requirements.txt": "pypi",
            "composer.lock": "composer", "Gemfile.lock": "gem", "Cargo.lock": "cargo", "go.mod": "go",
        }
        for path in FIXTURES.glob("*/*"):
            for dep in parse_lockfile(path).dependencies:
                self.assertTrue(dep["exact"], path)
                self.assertEqual(dep["type"], expected_type[path.name], path)
                self.assertEqual(dep["source"], str(path), path)

    def test_is_lockfile(self):
        for name in ["package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "poetry.lock",
                     "Pipfile.lock", "uv.lock", "composer.lock", "Gemfile.lock", "Cargo.lock", "go.mod"]:
            self.assertTrue(is_lockfile(Path(name)), name)
        for name in ["package.json", "requirements.txt", "Gemfile", "composer.json", "Cargo.toml"]:
            self.assertFalse(is_lockfile(Path(name)), name)

    def test_an_oversized_lockfile_is_refused(self):
        import lockfiles
        limit = lockfiles.MAX_LOCKFILE_BYTES
        lockfiles.MAX_LOCKFILE_BYTES = 100
        try:
            with self.assertRaisesRegex(LockfileError, "larger than"):
                parse_lockfile(FIXTURES / "npm3" / "package-lock.json")
        finally:
            lockfiles.MAX_LOCKFILE_BYTES = limit

    def test_a_broken_lockfile_raises_instead_of_returning_nothing(self):
        broken = FIXTURES.parent / "broken"
        broken.mkdir(exist_ok=True)
        try:
            for name, text in [("package-lock.json", "{not json"), ("Cargo.lock", "[[package]\nname = "),
                               ("composer.lock", "[]")]:
                (broken / name).write_text(text)
                with self.assertRaises(LockfileError, msg=name):
                    parse_lockfile(broken / name)
        finally:
            for f in broken.iterdir():
                f.unlink()
            broken.rmdir()


if __name__ == "__main__":
    unittest.main()
