class LineEndingsTest(unittest.TestCase):
    """Files edited or checked out on Windows use CRLF."""

    def crlf_copy(self, fixture, name):
        import tempfile
        directory = Path(tempfile.mkdtemp())
        self.addCleanup(__import__("shutil").rmtree, directory)
        target = directory / name
        target.write_bytes((FIXTURES / fixture / name).read_bytes().replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
        return target

    def test_go_mod_with_crlf_keeps_its_require_block(self):
        crlf = self.crlf_copy("gomod", "go.mod")
        self.assertIn(b"\r\n", crlf.read_bytes())
        deps, skipped = found("gomod", "go.mod")
        result = parse_lockfile(crlf)
        self.assertEqual({(d["name"], d["version"], d["scope"]) for d in result.dependencies}, deps)
        self.assertEqual(sorted(result.skipped), skipped)

    def test_every_fixture_parses_the_same_with_crlf(self):
        def summary(path):
            result = parse_lockfile(path)
            return sorted((d["name"], d["version"], d["scope"]) for d in result.dependencies), sorted(result.skipped)

        for path in FIXTURES.glob("*/*"):
            self.assertEqual(summary(self.crlf_copy(path.parent.name, path.name)), summary(path), path)


class RecordShapeTest(unittest.TestCase):
    def test_every_dependency_is_exact_typed_and_sourced(self):
        expected_type = {
            "package-lock.json": "npm", "pnpm-lock.yaml": "npm", "yarn.lock": "npm",
            "poetry.lock": "pypi", "Pipfile.lock": "pypi", "uv.lock": "pypi", "requirements.txt": "pypi",
            "composer.lock": "composer", "Gemfile.lock": "gem", "Cargo.lock": "cargo", "go.mod": "go",
        }
        for path in FIXTURES.glob("*/*"):
            for dep in parse_lockfile(path).dependencies:
                self.assertTrue(dep["exact"], path)
                self.assertEqual(dep["type"], expected_type[path.name], path)
                self.assertEqual(dep["source"], str(path), path)

    def test_is_lockfile(self):
        for name in ["package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "poetry.lock",
                     "Pipfile.lock", "uv.lock", "composer.lock", "Gemfile.lock", "Cargo.lock", "go.mod"]:
            self.assertTrue(is_lockfile(Path(name)), name)
        for name in ["package.json", "requirements.txt", "Gemfile", "composer.json", "Cargo.toml"]:
            self.assertFalse(is_lockfile(Path(name)), name)

    def test_an_oversized_lockfile_is_refused(self):
        import lockfiles
        limit = lockfiles.MAX_LOCKFILE_BYTES
        lockfiles.MAX_LOCKFILE_BYTES = 100
        try:
            with self.assertRaisesRegex(LockfileError, "larger than"):
                parse_lockfile(FIXTURES / "npm3" / "package-lock.json")
        finally:
            lockfiles.MAX_LOCKFILE_BYTES = limit

    def test_a_broken_lockfile_raises_instead_of_returning_nothing(self):
        broken = FIXTURES.parent / "broken"
        broken.mkdir(exist_ok=True)
        try:
            for name, text in [("package-lock.json", "{not json"), ("Cargo.lock", "[[package]\nname = "),
                               ("composer.lock", "[]")]:
                (broken / name).write_text(text)
                with self.assertRaises(LockfileError, msg=name):
                    parse_lockfile(broken / name)
        finally:
            for f in broken.iterdir():
                f.unlink()
            broken.rmdir()


class HostileInputTest(unittest.TestCase):
    """Whatever a repository contains, a parser fails with LockfileError and never crashes the scan."""

    def setUp(self):
        import tempfile
        self.dir = Path(tempfile.mkdtemp())
        self.addCleanup(__import__("shutil").rmtree, self.dir)

    def write(self, name, data):
        path = self.dir / name
        path.write_bytes(data)
        return path

    def test_utf16_requirements_raise_lockfile_error(self):
        path = self.write("requirements.txt", "requests==2.25.0\n".encode("utf-16"))
        with self.assertRaises(LockfileError):
            parse_lockfile(path)

    def test_latin1_gemfile_lock_raises_lockfile_error(self):
        path = self.write("Gemfile.lock", "GEM\n  specs:\n    caf\xe9 (1.0.0)\n".encode("latin-1"))
        with self.assertRaises(LockfileError):
            parse_lockfile(path)

    def test_deeply_nested_json_raises_lockfile_error(self):
        depth = 100000
        path = self.write("package-lock.json", b'{"dependencies":' * depth + b"{}" + b"}" * depth)
        with self.assertRaises(LockfileError):
            parse_lockfile(path)

    def test_yarn_blocks_with_many_blank_lines_parse_in_linear_time(self):
        import time
        blanks = "  \n" * 40000
        v1 = '# yarn lockfile v1\n\nfoo@^1.0.0:\n' + blanks + '\nbar@^1.0.0:\n  version "1.0.0"\n'
        berry = ('__metadata:\n  version: 6\n\n"foo@npm:^1.0.0":\n' + blanks +
                 '\n"bar@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "bar@npm:1.0.0"\n')
        for text in (v1, berry):
            path = self.write("yarn.lock", text.encode())
            started = time.perf_counter()
            result = parse_lockfile(path)
            self.assertLess(time.perf_counter() - started, 0.5)
            self.assertEqual([d["name"] for d in result.dependencies], ["bar"])

    def test_yarn_v1_alias_reports_the_real_package(self):
        text = ('# yarn lockfile v1\n\n"al@npm:bar@^2.0.0":\n  version "2.1.0"\n'
                '  resolved "https://registry.yarnpkg.com/bar/-/bar-2.1.0.tgz#abc"\n'
                '\n"@s/al@npm:@s/real@^1.0.0":\n  version "1.2.0"\n')
        result = parse_lockfile(self.write("yarn.lock", text.encode()))
        self.assertEqual([(d["name"], d["version"]) for d in result.dependencies], [("bar", "2.1.0"), ("@s/real", "1.2.0")])

    def test_a_utf8_bom_is_ignored(self):
        path = self.write("requirements.txt", b"\xef\xbb\xbfrequests==2.25.0\n")
        self.assertEqual([d["name"] for d in parse_lockfile(path).dependencies], ["requests"])
        path = self.write("package-lock.json", b'\xef\xbb\xbf{"packages": {"node_modules/a": {"version": "1.0.0"}}}')
        self.assertEqual([d["name"] for d in parse_lockfile(path).dependencies], ["a"])


