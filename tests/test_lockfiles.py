"""Lockfile parsing: exact installed versions, transitive dependencies included.

Every fixture under tests/fixtures/lockfiles was generated by the real tool for
its format (npm 6/8/10, pnpm 7/8/9, yarn 1/4, poetry, pipenv, uv, pip-compile,
composer, bundler, cargo) from a tiny synthetic manifest with one known-vulnerable
canary. Only go.mod is hand-written, as it is a file people edit.

Run with: python3 -m unittest discover -s tests
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lockfiles import LockfileError, _pnpm_key, _split_name_version, is_lockfile, parse_lockfile  # noqa: E402

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "lockfiles"


def found(fixture, filename):
    result = parse_lockfile(FIXTURES / fixture / filename)
    return {(d["name"], d["version"], d["scope"]) for d in result.dependencies}, sorted(result.skipped)


