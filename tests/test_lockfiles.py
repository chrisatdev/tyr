"""Lockfile parsing: exact installed versions, transitive dependencies included.

Every fixture under tests/fixtures/lockfiles was generated by the real tool for
its format (npm 6/8/10, pnpm 7/8/9, yarn 1/4, poetry, pipenv, uv, pip-compile,
composer, bundler, cargo) from a tiny synthetic manifest with one known-vulnerable
canary. Only go.mod is hand-written, as it is a file people edit.

Run with: python3 -m unittest discover -s tests
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lockfiles import LockfileError, _pnpm_key, _split_name_version, is_lockfile, parse_lockfile  # noqa: E402

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "lockfiles"


def found(fixture, filename):
    result = parse_lockfile(FIXTURES / fixture / filename)
    return {(d["name"], d["version"], d["scope"]) for d in result.dependencies}, sorted(result.skipped)


class NpmFamilyTest(unittest.TestCase):
    def test_package_lock_v1_nested_tree(self):
        deps, skipped = found("npm1", "package-lock.json")
        self.assertEqual(deps, {("minimist", "1.2.5", "prod"), ("is-number", "7.0.0", "dev")})

    def test_package_lock_v2(self):
        deps, _ = found("npm2", "package-lock.json")
        self.assertEqual(deps, {("minimist", "1.2.5", "prod"), ("is-number", "7.0.0", "dev")})

    def test_package_lock_v3_skips_local_links(self):
        deps, skipped = found("npm3", "package-lock.json")
        self.assertEqual(deps, {("minimist", "1.2.5", "prod"), ("is-number", "7.0.0", "dev")})
        self.assertEqual(skipped, ["local-lib"])

    def test_pnpm_v5_keys_with_slashes(self):
        deps, _ = found("pnpm5", "pnpm-lock.yaml")
        self.assertEqual(deps, {("minimist", "1.2.5", "prod"), ("is-number", "7.0.0", "dev")})

    def test_pnpm_v6_keys_with_at(self):
        deps, _ = found("pnpm6", "pnpm-lock.yaml")
        self.assertEqual(deps, {("minimist", "1.2.5", "prod"), ("is-number", "7.0.0", "dev")})

    def test_pnpm_v9_reads_packages_and_skips_local_dirs(self):
        deps, skipped = found("pnpm9", "pnpm-lock.yaml")
        self.assertEqual(deps, {("minimist", "1.2.5", None), ("is-number", "7.0.0", None)})
        self.assertEqual(skipped, ["local-lib"])

    def test_yarn_v1_skips_file_dependencies(self):
        deps, skipped = found("yarn1", "yarn.lock")
        self.assertEqual(deps, {("minimist", "1.2.5", None), ("is-number", "7.0.0", None)})
        self.assertEqual(skipped, ["local-lib"])

    def test_yarn_berry_skips_the_workspace_itself(self):
        deps, skipped = found("yarnberry", "yarn.lock")
        self.assertEqual(deps, {("minimist", "1.2.5", None), ("is-number", "7.0.0", None)})
        self.assertEqual(skipped, ["canary"])


class KeyShapesTest(unittest.TestCase):
    def test_pnpm_keys_across_lockfile_versions(self):
        cases = {
            "/is-number/7.0.0": ("is-number", "7.0.0"),                        # v5
            "/@babel/core/7.22.5": ("@babel/core", "7.22.5"),                  # v5 scoped
            "/@a/b/1.0.0_@types+node@20.1.0": ("@a/b", "1.0.0"),               # v5 peer suffix
            "/is-number@7.0.0": ("is-number", "7.0.0"),                        # v6
            "/@a/b@1.0.0(react@18.2.0)": ("@a/b", "1.0.0"),                    # v6 scoped + peer
            "'@cacheable/memory@2.2.0'": ("@cacheable/memory", "2.2.0"),        # v9 quoted scoped
            "minimist@1.2.5": ("minimist", "1.2.5"),                           # v9
            "pkg@git+ssh://git@github.com/o/r.git#abc": ("pkg", "git+ssh://git@github.com/o/r.git#abc"),
        }
        for key, expected in cases.items():
            self.assertEqual(_pnpm_key(key), expected, key)
        self.assertIsNone(_pnpm_key("github.com/owner/repo/0123abc"))  # v5 git entry

    def test_name_ends_at_the_first_at_after_the_scope(self):
        self.assertEqual(_split_name_version("fsevents@patch:fsevents@npm%3A2.3.2#hash"), ("fsevents", "patch:fsevents@npm%3A2.3.2#hash"))
        self.assertEqual(_split_name_version("@scope/name@npm:1.2.3"), ("@scope/name", "npm:1.2.3"))
        self.assertEqual(_split_name_version("name"), ("name", ""))


class PythonTest(unittest.TestCase):
    PYPI = {"certifi": "2026.10.23", "chardet": "3.0.4", "idna": "2.10", "requests": "2.25.0", "urllib3": "1.26.20"}

    def test_poetry_lock(self):
        deps, _ = found("poetry", "poetry.lock")
        expected = {(n, v, None) for n, v in self.PYPI.items()} | {("iniconfig", "2.0.0", None)}
        self.assertEqual(deps, expected)

    def test_pipfile_lock_separates_default_and_develop(self):
        deps, _ = found("pipenv", "Pipfile.lock")
        expected = {(n, v, "prod") for n, v in self.PYPI.items()} | {("iniconfig", "2.0.0", "dev")}
        self.assertEqual(deps, expected)

    def test_uv_lock_skips_the_virtual_project(self):
        deps, skipped = found("uv", "uv.lock")
        expected = {(n, v, None) for n, v in self.PYPI.items()} | {("iniconfig", "2.0.0", None)}
        self.assertEqual(deps, expected)
        self.assertEqual(skipped, ["canary"])

    def test_pip_compile_requirements_with_hashes(self):
        deps, _ = found("pipcompile", "requirements.txt")
        self.assertEqual(deps, {(n, v, None) for n, v in self.PYPI.items()})


